const CATALOGS: Record<string, Record<Key, string>> = { es, en };
export const UI_LANGUAGES = [
  { code: "es", name: "Español" },
  { code: "en", name: "English" },
];

type T = (key: Key, vars?: Record<string, string | number>) => string;
type I18n = { t: T; uiLanguage: string; setUiLanguage: (code: string) => void };

const Ctx = createContext<I18n>({ t: (k) => es[k], uiLanguage: "es", setUiLanguage: () => {} });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [uiLanguage, setUiLanguage] = useState("es");

  useEffect(() => {
    api.settings().then((s) => setUiLanguage(s.ui_language.value)).catch(() => {});
  }, []);

  useEffect(() => {
    document.documentElement.lang = uiLanguage;
  }, [uiLanguage]);

  const t = useCallback<T>(
    (key, vars) => {
      let text = (CATALOGS[uiLanguage] ?? es)[key] ?? es[key];
      for (const [k, v] of Object.entries(vars ?? {})) text = text.replace(`{${k}}`, String(v));
      return text;
    },
    [uiLanguage],
  );

  return <Ctx.Provider value={{ t, uiLanguage, setUiLanguage }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
